"""Core Pydantic data models for the multi-agent research assistant."""

from __future__ import annotations
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field
import time
import uuid


class Source(BaseModel):
    """A web source discovered and used by an agent."""
    id: str = Field(description="Unique source ID within report/section, e.g. S1, S2")
    url: str = Field(description="Web URL or document path")
    title: str = Field(default="", description="Page title or document name")
    snippet: str = Field(default="", description="Relevant extracted snippet or summary")
    backend: str = Field(default="ddg", description="Search engine/source that discovered this")
    published_date: Optional[str] = None


class SubTask(BaseModel):
    """A single sub-topic assigned to a researcher agent."""
    id: str = Field(description="Subtask identifier, e.g. subtask_1")
    title: str = Field(description="Short descriptive title of the subtopic")
    objective: str = Field(description="Goal of this sub-research")
    key_questions: List[str] = Field(default_factory=list, description="Questions the researcher must answer")
    suggested_queries: List[str] = Field(default_factory=list, description="Initial search queries")
    priority: int = Field(default=1, description="1 (high) to 3 (low)")


class ResearchPlan(BaseModel):
    """The overarching research plan produced by the Orchestrator."""
    topic: str
    interpretation: str = Field(description="How the orchestrator understood the topic and scope")
    audience: str = Field(default="General / Technical", description="Target audience or tone")
    scoping_sources: List[Source] = Field(default_factory=list, description="Initial web sources found during scoping")
    subtasks: List[SubTask] = Field(default_factory=list, description="List of sub-topics to research")
    final_report_outline: List[str] = Field(default_factory=list, description="Expected sections of the final report")


class SectionReport(BaseModel):
    """Report generated by a Researcher agent for a specific SubTask."""
    subtask_id: str
    title: str
    markdown: str = Field(description="Comprehensive markdown content citing sources like [S1], [S2]")
    key_findings: List[str] = Field(default_factory=list, description="Bullet points of key findings")
    open_questions: List[str] = Field(default_factory=list, description="Unanswered questions or knowledge gaps")
    sources: List[Source] = Field(default_factory=list, description="Sources cited in this section")
    confidence: Literal["low", "medium", "high"] = Field(default="medium")


class FactCheckItem(BaseModel):
    claim: str
    verdict: Literal["verified", "questionable", "unsubstantiated", "debunked"] = "verified"
    notes: str = ""
    source_url: Optional[str] = None


class Critique(BaseModel):
    """Critique generated by the Orchestrator when reviewing the Synthesizer draft."""
    approved: bool = Field(description="True if report meets quality and coverage standards")
    issues: List[str] = Field(default_factory=list, description="Identified inconsistencies, gaps, or style issues")
    missing_coverage: List[str] = Field(default_factory=list, description="Important aspects missing from the plan")
    fact_checks: List[FactCheckItem] = Field(default_factory=list, description="Web fact-checks of key claims")
    instructions_for_revision: str = Field(default="", description="Actionable revision instructions for Synthesizer")


class AnnotationIntent(str, Enum):
    RESEARCH_MORE = "research_more"
    FACT_CHECK = "fact_check"
    REWRITE = "rewrite"
    EXPAND = "expand"
    REMOVE = "remove"
    AUTO = "auto"


class Annotation(BaseModel):
    """User highlight and comment in the report viewer."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    report_version: int = 1
    quote: str = Field(description="Selected text quote")
    prefix: str = Field(default="", description="Text immediately preceding selection (for robust re-anchoring)")
    suffix: str = Field(default="", description="Text immediately following selection")
    line_start: int = Field(default=0, description="Approximate markdown starting line")
    line_end: int = Field(default=0, description="Approximate markdown ending line")
    comment: str = Field(description="User feedback comment")
    intent: AnnotationIntent = AnnotationIntent.AUTO
    created_at: float = Field(default_factory=time.time)


class FeedbackAction(BaseModel):
    annotation_id: str
    action: Literal["research", "fact_check", "rewrite", "expand", "delete", "skip"]
    details: str
    suggested_query: Optional[str] = None


class FeedbackPlan(BaseModel):
    """Plan generated by Feedback Triage agent based on user annotations."""
    actions: List[FeedbackAction] = Field(default_factory=list)
    subtasks_to_add: List[SubTask] = Field(default_factory=list)
    rewrite_instructions: str = ""


class RunState(str, Enum):
    INITIALIZING = "initializing"
    PLANNING = "planning"
    AWAITING_PLAN_REVIEW = "awaiting_plan_review"
    RESEARCHING = "researching"
    AWAITING_SECTIONS_REVIEW = "awaiting_sections_review"
    SYNTHESIZING = "synthesizing"
    REVIEWING = "reviewing"
    AWAITING_DRAFT_REVIEW = "awaiting_draft_review"
    DONE = "done"
    REVISING = "revising"
    FAILED = "failed"
    CANCELLED = "cancelled"


class AgentEvent(BaseModel):
    """Event emitted during pipeline execution for live GUI updates."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    run_id: str
    timestamp: float = Field(default_factory=time.time)
    stage: str
    agent_id: str
    agent_name: str
    status: Literal["started", "running", "progress", "completed", "warning", "error"] = "running"
    message: str
    data: Optional[Dict[str, Any]] = None


class CheckpointAction(BaseModel):
    """Action submitted by user at a checkpoint."""
    stage: Literal["plan", "sections", "draft"]
    action: Literal["approve", "edit", "feedback"]
    feedback_text: Optional[str] = None
    edited_data: Optional[Dict[str, Any]] = None


class TokenUsage(BaseModel):
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    estimated_cost_usd: float = 0.0


class RunSummary(BaseModel):
    """High-level summary of a research run."""
    run_id: str
    topic: str
    extra_instructions: str = ""
    depth: Literal["quick", "standard", "deep"] = "standard"
    checkpoint_mode: Literal["all", "plan_only", "autopilot"] = "all"
    state: RunState = RunState.INITIALIZING
    created_at: float = Field(default_factory=time.time)
    updated_at: float = Field(default_factory=time.time)
    completed_at: Optional[float] = None
    total_sources: int = 0
    active_agent_count: int = 0
    current_version: int = 1
    token_usage: TokenUsage = Field(default_factory=TokenUsage)
    error_message: Optional[str] = None
